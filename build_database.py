with open('full_user_input.txt', 'r', encoding='utf-8') as f:
    full_text = f.read()

months = ['መስከረም', 'ጥቅምት', 'ኅዳር', 'ህዳር', 'ታኅሳስ', 'ታህሳስ', 'ጥር', 'የካቲት', 'መጋቢት', 'ሚያዝያ', 'ሚያዚያ', 'ግንቦት', 'ሰኔ', 'ሐምሌ', 'ነሐሴ', 'ነሃሴ']
m_str = '|'.join(months)
pattern = r'(' + m_str + r')\s*([፩-፴\d\s]+?)\s*(?:ቀን)?\s*(?:የሚከበሩ|ሚከበሩ|የሚከቀሩ|ነሚከበሪ|የ\s*ቅዱሳን|በዓላት)'

matches = list(re.finditer(pattern, full_text))
parsed_entries = {} # (mon, day_int) -> (annual_list, monthly_list)

for i, m in enumerate(matches):
    raw_m = m.group(1).replace('ኅዳር', 'ህዳር').replace('ታኅሳስ', 'ታህሳስ').replace('ሚያዝያ', 'ሚያዚያ').replace('ነሃሴ', 'ነሐሴ')
    raw_d = m.group(2).strip().replace(' ', '')
    d_int = geez_to_int.get(raw_d)
    if not d_int:
        continue
    
    st_idx = m.end()
    end_idx = matches[i+1].start() if i+1 < len(matches) else len(full_text)
    chunk = full_text[st_idx:end_idx].strip()
    
    # Split chunk into annual and monthly
    # Monthly markers: 'ወርኀዊ', 'ወርኃዊ', 'ወርሃዊ', 'ወርሐዊ'
    split_m = re.search(r'ወር[ኀኃርሃሐ]ዊ\s*(?:የቅዱሳን\s*)?በዓላት?', chunk)
    if split_m:
        ann_text = chunk[:split_m.start()].strip()
        mon_text = chunk[split_m.end():].strip()
    else:
        ann_text = chunk
        mon_text = ''
        
    def clean_items(txt):
        lines = [ln.strip() for ln in txt.split('\n') if ln.strip()]
        items = []
        for ln in lines:
            # remove redundant headers or symbols
            if re.match(r'^(?:ዓመታዊ|ወር[ኀኃርሃሐ]ዊ|የቅዱሳን|በዓላት|=+|-+)', ln):
                continue
            # Clean punctuation at start if needed
            # normalize colon or period after Geez number
            ln = re.sub(r'^([፩-፴\d]+)[\.፡:]\s*', r'\1. ', ln)
            ln = re.sub(r'^([፩-፴\d]+)\s+', r'\1. ', ln)
            items.append(ln)
        return items

    ann_items = clean_items(ann_text)
    mon_items = clean_items(mon_text)
    
    # Store if not already stored or has more items
    if (raw_m, d_int) not in parsed_entries or len(ann_items) > len(parsed_entries[(raw_m, d_int)][0]):
        parsed_entries[(raw_m, d_int)] = (ann_items, mon_items)

print(f'Total parsed from user input: {len(parsed_entries)}')

