def process_all_user_data():
    print(f"Starting processing of {len(USER_NEW_DATA)} dates from user screenshots...")
    conn = db.get_db_connection()
    cursor = conn.cursor()

    years = [2018, 2019]

    for (raw_m_name, d), data in USER_NEW_DATA.items():
        norm_m = MONTH_ALIAS.get(raw_m_name, raw_m_name)
        m_idx = ec.MONTH_NAME_TO_INDEX.get(norm_m)
        if not m_idx:
            print(f"Unknown month {raw_m_name} (normalized: {norm_m})")
            continue

        geez = data["geez"]
        annual = data["annual"]
        monthly = data["monthly"]

        # 1. ጽሑፉን ማዘጋጀት
        ann_text = "\n".join(annual)
        mon_text = "\n".join(monthly)

        body_parts = []
        if ann_text.strip():
            body_parts.append(ann_text.strip())
        if mon_text.strip():
            body_parts.append(f"ወርኃዊ በዓላት\n\n{mon_text.strip()}")

        raw_body = "\n\n".join(body_parts)

        # 2. ለእያንዳንዱ ዓመት ፖስተር ማመንጨት እና ፋይሎችን መተካት
        for y in years:
            year_dir = cm.ensure_year_structure(y)
            m_meta = ec.get_month_info(m_idx)
            day_folder = year_dir / m_meta["prefix"] / f"{d:02d}"
            day_folder.mkdir(parents=True, exist_ok=True)

            # የጽሑፍ ፋይል መጻፍ (text.txt)
            txt_path = day_folder / "text.txt"
            txt_path.write_text(raw_body, encoding="utf-8")

            # አዲስ ሰማያዊ/ቢጫ ፖስተር ማመንጨት
            img_path = day_folder / "image.jpg"
            try:
                render_sinkisar_image(norm_m, geez, annual, monthly, str(img_path))
            except Exception as e:
                print(f"Render error for {norm_m} {d}: {e}")

            # ዳታቤዝ ላይ UPDATE ማድረግ
            cursor.execute("""
            UPDATE synksar_content
            SET amharic_text = ?, image_path = ?, updated_at = CURRENT_TIMESTAMP
            WHERE eth_year = ? AND eth_month = ? AND eth_day = ?;
            """, (raw_body, str(img_path), y, m_idx, d))

        print(f"✅ {norm_m} {d} ({geez}) - Updated successfully in files, images, and database!")

    conn.commit()
    conn.close()
    print("=" * 60)
    print("🎉 All 31 dates fully replaced with user's exact data!")
    print("=" * 60)


if __name__ == "__main__":
    process_all_user_data()
